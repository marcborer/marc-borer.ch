/**
 * Fetch Google Fonts as self-hosted WOFF2 files.
 * Runs before every build. Falls back to existing files if fetch fails.
 *
 * Config: edit the FONTS array below to change families, axes and subsets.
 * `axes` is the Google Fonts css2 axis spec after the colon, e.g.
 *   'wght@400;500;600'            static weights
 *   'wdth,wght@100..125,400..800' variable ranges (axes alphabetical)
 */

import { writeFileSync, mkdirSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const FONTS_DIR = join(ROOT, 'public', 'fonts');
const CSS_OUTPUT = join(ROOT, 'src', 'styles', 'fonts.css');

// ---- Font configuration ----
const FONTS = [
  { family: 'Archivo', axes: 'wdth,wght@100..125,400..800' },
  { family: 'IBM Plex Sans', axes: 'wght@400;500;600' },
  { family: 'IBM Plex Mono', axes: 'wght@400;500' },
];

// Only ship the subsets the site renders (German + English copy).
const SUBSETS = new Set(['latin', 'latin-ext']);

const CHROME_UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

async function fetchGoogleCSS() {
  const families = FONTS.map(f => `family=${f.family.replace(/ /g, '+')}:${f.axes}`).join('&');
  const url = `https://fonts.googleapis.com/css2?${families}&display=swap`;

  const res = await fetch(url, { headers: { 'User-Agent': CHROME_UA } });
  if (!res.ok) throw new Error(`Google Fonts API returned ${res.status}`);
  return res.text();
}

function parseFontFaces(css) {
  const faces = [];
  const regex = /\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]+)\}/g;
  let match;

  while ((match = regex.exec(css)) !== null) {
    const subset = match[1]; // e.g. "latin", "latin-ext"
    const block = match[2];

    const family = block.match(/font-family:\s*'([^']+)'/)?.[1];
    const weight = block.match(/font-weight:\s*([^;]+);/)?.[1]?.trim();
    const stretch = block.match(/font-stretch:\s*([^;]+);/)?.[1]?.trim();
    const srcUrl = block.match(/url\(([^)]+)\)/)?.[1];
    const unicodeRange = block.match(/unicode-range:\s*([^;]+)/)?.[1]?.trim();

    if (family && weight && srcUrl && unicodeRange && SUBSETS.has(subset)) {
      faces.push({ family, weight, stretch, subset, srcUrl, unicodeRange });
    }
  }
  return faces;
}

function buildFilename(family, subset, srcUrl) {
  // A variable font serves every weight from one file; static families serve one file per weight.
  // Key the filename on the source URL's hash so static weights do not overwrite each other.
  const id = srcUrl.split('/').pop().replace(/\.woff2$/, '').slice(-8);
  return `${family.toLowerCase().replace(/ /g, '-')}-${subset}-${id}.woff2`;
}

async function downloadFont(url, destPath) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Failed to download ${url}: ${res.status}`);
  const buffer = Buffer.from(await res.arrayBuffer());
  writeFileSync(destPath, buffer);
}

function generateCSS(faces) {
  // Group by file: a variable font carries a weight range; static faces carry one weight each.
  const groups = new Map();
  for (const face of faces) {
    const filename = buildFilename(face.family, face.subset, face.srcUrl);
    if (!groups.has(filename)) {
      groups.set(filename, { ...face, filename, weights: new Set() });
    }
    for (const w of face.weight.split(/\s+/)) groups.get(filename).weights.add(Number(w));
  }

  let css = '/* Auto-generated by scripts/fetch-fonts.mjs — do not edit manually */\n\n';

  for (const group of groups.values()) {
    const ws = [...group.weights];
    const weight = ws.length > 1 ? `${Math.min(...ws)} ${Math.max(...ws)}` : String(ws[0]);
    css += `/* ${group.family} — ${group.subset} */\n`;
    css += `@font-face {\n`;
    css += `  font-family: '${group.family}';\n`;
    css += `  font-style: normal;\n`;
    css += `  font-weight: ${weight};\n`;
    if (group.stretch) css += `  font-stretch: ${group.stretch};\n`;
    css += `  font-display: swap;\n`;
    css += `  src: url('/fonts/${group.filename}') format('woff2');\n`;
    css += `  unicode-range: ${group.unicodeRange};\n`;
    css += `}\n\n`;
  }

  return css;
}

async function main() {
  console.log('[fonts] Fetching Google Fonts CSS...');

  let css;
  try {
    css = await fetchGoogleCSS();
  } catch (err) {
    console.warn(`[fonts] Fetch failed: ${err.message}`);
    if (existsSync(CSS_OUTPUT)) {
      console.log('[fonts] Using existing fonts as fallback.');
      return;
    }
    throw new Error('[fonts] No fallback fonts available. Build cannot continue.');
  }

  const faces = parseFontFaces(css);
  if (faces.length === 0) {
    console.warn('[fonts] No font faces parsed. Using existing fonts as fallback.');
    return;
  }

  console.log(`[fonts] Found ${faces.length} font faces. Downloading WOFF2 files...`);

  mkdirSync(FONTS_DIR, { recursive: true });

  const downloaded = new Set();
  for (const face of faces) {
    const filename = buildFilename(face.family, face.subset, face.srcUrl);
    if (downloaded.has(filename)) continue;
    downloaded.add(filename);

    const destPath = join(FONTS_DIR, filename);
    try {
      await downloadFont(face.srcUrl, destPath);
      console.log(`[fonts]   ✓ ${filename}`);
    } catch (err) {
      console.warn(`[fonts]   ✗ ${filename}: ${err.message}`);
      if (existsSync(destPath)) {
        console.log(`[fonts]     Using existing file as fallback.`);
      }
    }
  }

  writeFileSync(CSS_OUTPUT, generateCSS(faces));
  console.log(`[fonts] Generated ${CSS_OUTPUT.replace(ROOT, '')}`);
  console.log('[fonts] Done.');
}

main().catch(err => {
  console.error(err.message);
  process.exit(1);
});
